"""Ошибки ядра.

Текст ошибки видит игрок, поэтому он по-английски (D36).
"""


class RuleError(Exception):
    """Действие нарушает правила мира, и ядро его не выполнило."""


class NotFoundError(RuleError):
    """Нет такого персонажа, места, предмета или факта."""


class SchemaError(Exception):
    """Файл мира создан другой версией программы или повреждён."""
